export const formatLocationAreaName = (rawName) => {
  if (!rawName) return '';
  return rawName
    .replace(/-area$/i, '')
    .replace(/^kanto-/, '')
    .replace(/^johto-/, '')
    .replace(/^hoenn-/, '')
    .replace(/^sinnoh-/, '')
    .replace(/^unova-/, '')
    .replace(/^kalos-/, '')
    .replace(/^alola-/, '')
    .replace(/^galar-/, '')
    .replace(/^hisui-/, '')
    .replace(/^paldea-/, '')
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
};

