/**
 * Inverted Lookup Helper:
 * Find every location across all bundled regions where a specific Pokémon is found!
 */
export const findPokemonLocations = (pokemonIdOrName) => {
  if (!pokemonIdOrName) return [];
  const query = String(pokemonIdOrName).toLowerCase().trim();

  const results = [];
  LOCATION_DEX.forEach((loc) => {
    const matchingEncounters = loc.encounters.filter((enc) => {
      const matchId = String(enc.id) === query;
      const matchName = enc.name.toLowerCase().includes(query);
      return matchId || matchName;
    });

    if (matchingEncounters.length > 0) {
      results.push({
        location: loc,
        encounters: matchingEncounters,
      });
    }
  });

  return results;
};
