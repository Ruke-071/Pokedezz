export const ARCEUS_PLATES_MAP = ARCEUS_PLATES.reduce((acc, plate) => {
  acc[plate.type] = plate;
  acc[plate.id] = plate;
  return acc;
}, {});

/**
 * Helper to retrieve Plate metadata for any Pokémon type
 */
export const getArceusPlateByType = (type) => {
  if (!type) return ARCEUS_PLATES[0];
  const clean = type.toLowerCase().trim();
  return ARCEUS_PLATES_MAP[clean] || ARCEUS_PLATES[0];
};
